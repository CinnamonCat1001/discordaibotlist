#!/usr/bin/env python3
"""Generate README.md from bots.json. Stdlib only. Run: python3 scripts/generate_readme.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOTS = ROOT / "bots.json"
README = ROOT / "README.md"

HEADER = """# discordaibotlist
this is a list of all tiktok ai slop all in one moderatino bots. that popped up recently and advertise similarly.

> Edit `bots.json`, not this file. README is auto-generated by `scripts/generate_readme.py` (see `.github/workflows/generate-readme.yml`).

"""


def label(url, text):
    return f"[{text}]({url})" if url else text


def row(b):
    name = b["name"]
    tiktok = b.get("tiktok")
    left = f"[{name}]({tiktok})" if tiktok else f"({name})"
    parts = [left, label(b.get("web"), "Web"), label(b.get("discord"), "Discord")]
    line = "+ " + " | ".join(parts)
    if b.get("notes"):
        line += f" ({b['notes']})"
    return line


def main():
    bots = json.loads(BOTS.read_text())
    bots.sort(key=lambda b: b["name"].lower())
    README.write_text(HEADER + "\n".join(row(b) for b in bots) + "\n")


if __name__ == "__main__":
    main()
    assert README.exists()  # ponytail: single runnable check
